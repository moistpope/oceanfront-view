#!/usr/bin/env python3
"""Build static/js/borders_data.js (the country borders region.js looks the car's position up in) from world-atlas's
countries-50m.json (Natural Earth 1:50m, public domain; world-atlas ISC). Usage:
  npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz
  python3 tools/make_borders.py package/countries-50m.json static/js/borders_data.js
Each country: [id, name, ring, ring, ...], id the ISO 3166 numeric code ('' where Natural Earth has none), each ring
its points on the file's integer grid (lon = -180 + x * SCALE[0], lat = ORIGIN[1] + y * SCALE[1]), delta-encoded."""
import json, sys

src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src))
sx, sy = d['transform']['scale']
tx, ty = d['transform']['translate']
arcs = []
for a in d['arcs']:   # quantized topojson: each arc's points are deltas
    x = y = 0
    pts = []
    for dx, dy in a:
        x += dx; y += dy
        pts.append((x, y))
    arcs.append(pts)

def arc(i):
    return arcs[i] if i >= 0 else arcs[~i][::-1]

def ring(idx):
    out = []
    for i in idx:
        pts = arc(i)
        out.extend(pts if not out else pts[1:])
    if len(out) > 1 and out[0] == out[-1]:
        out.pop()
    return out

countries = []
for g in d['objects']['countries']['geometries']:
    name = g['properties']['name']
    if name == 'Antarctica' or g['type'] not in ('Polygon', 'MultiPolygon'):
        continue
    polys = g['arcs'] if g['type'] == 'MultiPolygon' else [g['arcs']]
    rings = []
    for p in polys:
        for r in p:
            pts = ring(r)
            if len(pts) < 3:
                continue
            flat, px, py = [], 0, 0
            for x, y in pts:
                flat += [x - px, y - py]; px, py = x, y
            rings.append(flat)
    countries.append([g.get('id') or '', name] + rings)

with open(dst, 'w') as f:
    f.write('// Country borders for region.js: Natural Earth 1:50m (public domain) by way of world-atlas 2.0.2\n')
    f.write('// (ISC, Copyright 2013-2019 Michael Bostock). Generated by tools/make_borders.py; do not edit.\n')
    f.write(f'export const SCALE = [{sx!r}, {sy!r}];\nexport const ORIGIN = [{tx!r}, {ty!r}];\n')
    f.write('export const COUNTRIES = ')
    json.dump(countries, f, separators=(',', ':'), ensure_ascii=False)
    f.write(';\n')
